"use strict";
const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const read = (path) => fs.readFileSync(path, "utf8");
const site = read("index.html");
const backendSite = read("public/index.html");
const adminHtml = read("public/admin.html");
const adminJs = read("public/admin.js");
const serverJs = read("server.js");
assert.equal(site, backendSite, "Root and backend storefront copies must stay identical.");
assert.equal(read("i18n.js"), read("public/i18n.js"), "Root and backend language files must stay identical.");
const ids = [...site.matchAll(/\bid=["']([^"']+)["']/g)].map((m) => m[1]);
const idSet = new Set(ids);
assert.equal(ids.length, idSet.size, "Customer storefront contains duplicate HTML IDs.");
for (const match of site.matchAll(/getElementById\(["']([^"']+)["']\)/g)) assert.ok(idSet.has(match[1]), "Missing customer DOM id: " + match[1]);
const adminIds = new Set([...adminHtml.matchAll(/\bid=["']([^"']+)["']/g)].map((m) => m[1]));
for (const match of adminJs.matchAll(/\$\(["']([^"']+)["']\)/g)) assert.ok(adminIds.has(match[1]), "Missing admin DOM id: " + match[1]);
for (const match of site.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) if (!/\bsrc\s*=/.test(match[1])) new vm.Script(match[2], { filename: "index.html inline script" });
new vm.Script(adminJs, { filename: "public/admin.js" });
new vm.Script(serverJs, { filename: "server.js" });
JSON.parse(read("manifest.webmanifest"));
assert.ok(site.includes('value="COMPUTER_SERVICE"'), "Computer service request option is missing.");
assert.ok(site.includes('id="shoppingPolicies"'), "Shopping policy section is missing.");
assert.ok(site.includes("ফুলবাড়িয়া ও গড়বেতায় লোকাল ডেলিভারি"), "Local delivery offer is missing.");
assert.ok(!/রিচার্জ|বিল পে|bill payment|Recharge Zone|rechargeHub|data-open-recharge/i.test(site), "Recharge or bill-payment UI remains in the storefront.");
assert.ok(serverJs.includes("const orderRequestLimit="), "Order rate limit is missing.");
assert.ok(site.includes('id="guestCheckoutFields"'), "Public website guest checkout fields are missing.");
assert.ok(site.includes("html:not(.app-mode) .account-panel"), "Customer account must be hidden on the public website.");
assert.ok(!site.includes('id="loginPassword"') && !site.includes('id="setPasswordArea"'), "Customer login must use OTP only.");
assert.ok(serverJs.includes('orderSource:user?"ANDROID_APP":"PUBLIC_WEBSITE"'), "Orders must record their source.");
assert.ok(serverJs.includes("const quantities=new Map()"), "Duplicate cart items are not normalized before stock reservation.");
assert.ok(serverJs.includes('["NEW","CONFIRMED","PROCESSING","SHIPPED","DELIVERED","CANCELLED"]'), "Backend processing order status is missing.");
assert.ok(adminJs.includes('["NEW","CONFIRMED","PROCESSING","SHIPPED","DELIVERED","CANCELLED"]'), "Admin processing order status is missing.");
assert.ok(adminJs.includes('PROCESSING:"প্রসেসিং"'), "Admin processing status label is missing.");
console.log("Shivam Network checks passed: storefront sync, DOM references, JavaScript syntax, policy, local delivery, service options and order validation.");
